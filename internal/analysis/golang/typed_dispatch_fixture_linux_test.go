func runTypedDispatchFixture(t *testing.T, ctx context.Context, parent, goRoot string, tool *runtimeadapter.GoExecutable) {
	t.Helper()
	dir := filepath.Join(parent, "typed-dispatch")
	for _, name := range []string{"input", "cache", "modcache", "gopath", "home", "tmp"} {
		if err := os.MkdirAll(filepath.Join(dir, name), 0700); err != nil {
			t.Fatal(err)
		}
	}
	const source = `// Code generated by fixture. DO NOT EDIT.
package fixture
type Runner interface { Run(int) int }
type A struct{}
func (A) Run(x int) int { return x }
type B struct{}
func (*B) Run(x int) int { return x + 1 }
type State struct { Count int }
func Direct(x int) int { return x }
var Global = Direct(10)
func _() { Direct(9) }
func Use(r Runner, fn func(int) int) int {
	x := r.Run(1)
	y := A{}.Run(2)
	z := fn(3)
	n := int(x)
	w := Runner.Run(r, 4)
	q := Direct(5)
	q2 := Direct(6)
	x += q
	ptr := &x
	*ptr = q
	s := State{}
	s.Count = q
	addr := &s.Count
	_ = addr
	closure := func(v int) int { return v }
	fromClosure := closure(7)
	immediate := func(v int) int { return v }(8)
	return x + y + z + n + w + q2 + fromClosure + immediate
}
`
	contents := map[string]string{"go.mod": "module example.test/fixture\n\ngo 1.27.4\n", "dispatch.go": source,
		"dispatch_test.go": "package fixture\nfunc TestReference() { _ = Direct(1) }\n",
		"client.ts":        "const apparentCall = 'Direct(1)'\n", "query.sql": "SELECT 'Direct(1)'\n"}
	for name, value := range contents {
		if err := os.WriteFile(filepath.Join(dir, "input", name), []byte(value), 0600); err != nil {
			t.Fatal(err)
		}
	}
	input := loaderPreflightFixture(t, contents)
	input.VerifyClosure = func(context.Context, *snapshot.Snapshot, inventory.FileMap) (bool, error) { return true, nil }
	input.VerifyToolchain = LoaderToolchainVerifier(tool, goRoot, func(context.Context, *model.GoProfile) (bool, error) { return true, nil })
	root, err := paths.OpenRoot(dir)
	if err != nil {
		t.Fatal(err)
	}
	defer root.Close()
	request := TypedInput{Loader: CapturedLoaderInput{Preflight: input, GoRoot: goRoot, ScratchRoot: dir, WorkspaceRoot: filepath.Join(dir, "input"), Tool: tool, MaxOutputBytes: 65536,
		VerifyScratch: LoaderScratchVerifier(root, func(context.Context) error { return nil })}, PackageKey: "dispatch-package", ModuleKey: "fixture-module", MaxNodes: 10000, MaxDepth: 256, MaxFacts: 1000, MaxOccurrences: 1000, MaxOutputBytes: 256 * 1024}
	result, err := AnalyzeTypedCaptured(ctx, request)
	if err != nil || len(result.Syntax) != 1 || !containsReason(result.Reasons, "INTERFACE_CANDIDATES_SCOPED") {
		t.Fatalf("typed dispatch fixture: %+v %v", result, err)
	}
	var ids []string
	for _, symbol := range result.Syntax[0].Symbols {
		if symbol.Kind == "method" && symbol.Name == "Run" && symbol.Range != nil && (symbol.Range.StartByte == int64(strings.Index(source, "func (A) Run")+len("func (A) ")) || symbol.Range.StartByte == int64(strings.Index(source, "func (*B) Run")+len("func (*B) "))) {
			ids = append(ids, symbol.SymbolID)
		}
	}
	sort.Strings(ids)
	if len(ids) != 2 || ids[0] == ids[1] {
		t.Fatal("candidate method identities missing")
	}
	for _, marker := range []struct{ fragment, prefix, dispatch, selection string }{{"r.Run", "r.", "interface", "method_value"}, {"A{}.Run", "A{}.", "concrete", "method_value"}, {"Runner.Run", "Runner.", "interface", "method_expression"}} {
		position := strings.Index(source, marker.fragment) + len(marker.prefix)
		found := false
		for _, occurrence := range result.Occurrences {
			if occurrence.Kind != "use" || occurrence.Name != "Run" || occurrence.Range.StartByte != int64(position) {
				continue
			}
			found = occurrence.Dispatch == marker.dispatch && occurrence.Selection == marker.selection && occurrence.ObjectKind == "function"
			if marker.dispatch == "interface" {
				found = found && len(occurrence.Candidates) == 2 && occurrence.Candidates[0] == ids[0] && occurrence.Candidates[1] == ids[1]
			} else {
				found = found && len(occurrence.Candidates) == 0
			}
		}
		if !found {
			t.Fatalf("wrong dispatch at %s", marker.fragment)
		}
	}
	conversion := strings.Index(source, "int(x)")
	call := strings.Index(source, "r.Run(1)")
	gotConversion, gotCall := false, false
	for _, site := range result.Calls {
		gotConversion = gotConversion || site.Range.StartByte == int64(conversion) && site.Kind == "conversion"
		gotCall = gotCall || site.Range.StartByte == int64(call) && site.Kind == "call"
	}
	if !gotConversion || !gotCall {
		t.Fatal("call and conversion were not distinguished")
	}
	runGraphDispatchFixture(t, ctx, request, source, ids)
	runCoverageFixture(t, ctx, request, source)
	runTestReferencesPublicationFixture(t, ctx)
}
